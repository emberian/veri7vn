package veri7vn.workbench
import scala.language.unsafeNulls
import java.nio.file.{Files,Path}
import java.nio.charset.StandardCharsets.UTF_8
import veri7vn.runtime.host.{WorkspaceStore,ManagedSources}
import veri7vn.packages.intake.Intake
import veri7vn.packages.lifecycle.ManagedDrafts
object AuthoringTests {
  def main(args:Array[String]):Unit={
    val root=Files.createTempDirectory("v7-author-client-").toRealPath()
    val source=Files.createTempDirectory("v7-author-source-").toRealPath()
    val text="theory Custom imports Main begin\n(* expert block untouched *)\nlemma preserved: True by simp\nend\n"
    Files.write(source.resolve("Custom.thy"),text.getBytes(UTF_8))
    Files.write(source.resolve("package.json"),"{}".getBytes(UTF_8))
    val store=new WorkspaceStore(root)
    try {
      val managed=new ManagedSources(store)
      val client=new Authoring(managed)
      assert(client.list().isEmpty)
      assert(client.importSource("import1","custom",source,Intake.Format.NativeDevelopment).isInstanceOf[ManagedDrafts.Recorded])
      assert(client.list()==Vector("custom"))
      val current=client.source("custom","Custom.thy")
      val start=text.indexOf("expert block")
      assert(client.edit("edit1","custom",current.snapshot.manifest,current.snapshot.revision.id,"Custom.thy",start,start+12,
        "expert block".getBytes(UTF_8),"custom expert block".getBytes(UTF_8)).isInstanceOf[ManagedDrafts.Recorded])
      val next=client.source("custom","Custom.thy")
      assert(next.text.contains("lemma preserved: True by simp"))
      assert(client.list()==Vector("custom"))
      assert(next.text.contains("custom expert block untouched"))
      val diagnostic=SourceLocation.locate(current.snapshot,"Custom.thy",start,start+12,next.snapshot.revision.id)
      assert(diagnostic.line==2 && diagnostic.column==4 && !diagnostic.current)
      var foreign=false;try SourceLocation.locate(current.snapshot,"Other.thy",0,1,current.snapshot.revision.id)
        catch {case _:IllegalArgumentException=>foreign=true};assert(foreign)

      assert(client.edit("stale","custom",current.snapshot.manifest,current.snapshot.revision.id,"Custom.thy",start,start+12,
        "expert block".getBytes(UTF_8),"bad".getBytes(UTF_8))==ManagedDrafts.Conflict)
      val original=Path.of("upstream/workbench/examples/paint-coverage")
      assert(client.importSource("original1","paint",original,Intake.Format.Oracle7Original).isInstanceOf[ManagedDrafts.Recorded])
      assert(client.migration("paint").candidates.nonEmpty)
      assert(client.panel("paint").rows.size==18)
      assert(client.list()==Vector("custom","paint"))
      var overflow=false;try client.list(1) catch {case _:IllegalArgumentException=>overflow=true};assert(overflow)
      assert(client.importSource("temporary1","temporary",source,Intake.Format.NativeDevelopment).isInstanceOf[ManagedDrafts.Recorded])
      managed.forget("temporary")
      assert(client.list()==Vector("custom","paint"))
      val growth=Path.of("examples/growth/retained-identity")
      assert(client.importSource("growth1","identity",growth,Intake.Format.NativeDevelopment).isInstanceOf[ManagedDrafts.Recorded])
      assert(client.describe("identity").descriptor.exports.isEmpty)
      assert(client.source("identity","OBLIGATIONS.md").text.nonEmpty)
      def dependencyFixture(draft:String,id:String,dependency:String,version:String="0.1.0"):Unit={
        val directory=Files.createTempDirectory("v7-impact-source-").toRealPath()
        val required=if(dependency.isEmpty)"[]"else "[{\"package_id\":\""+dependency+"\",\"version\":\""+version+"\"}]"
        val descriptor="{\"format\":\"veri7vn.package/0\",\"package\":{\"id\":\""+id+"\",\"version\":\"0.1.0\",\"title\":\"Impact fixture\",\"description\":\"Source declaration fixture\"},\"files\":[{\"path\":\"note.md\",\"role\":\"documentation\"}],\"requires\":"+required+",\"capabilities\":[]}"
        Files.writeString(directory.resolve("package.json"),descriptor)
        Files.writeString(directory.resolve("note.md"),"inert source declaration")
        client.importSource("import-"+draft,draft,directory,Intake.Format.NativeDevelopment)
      }
      dependencyFixture("consumer","veri7vn.consumer","veri7vn.retained-identity")
      dependencyFixture("transitive","veri7vn.transitive","veri7vn.consumer")
      dependencyFixture("different-version","veri7vn.other","veri7vn.retained-identity","0.2.0")
      val impact=client.impact("identity")
      assert(impact.affected.map(_.consumer.draft)==Vector("consumer","transitive"))
      assert(impact.affected.last.pathToTarget==Vector("transitive","consumer","identity"))
      assert(impact.issues.exists(_.isInstanceOf[veri7vn.diagnostics.PackageImpact.Issue.MissingProvider]))
      assert(!client.impact("custom").computed)
      val browser=new Browser(client);browser.start()
      try {
        val http=java.net.http.HttpClient.newHttpClient()
        val response=http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url)).GET().build(),java.net.http.HttpResponse.BodyHandlers.ofString())
        assert(response.statusCode()==200 && response.body().contains("Specialist workspace"))
        val token="name=\"token\" value=\"([^\"]+)".r.findFirstMatchIn(response.body()).get.group(1)
        def getWorkspace(query:String):String=http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url+query)).GET().build(),java.net.http.HttpResponse.BodyHandlers.ofString()).body()
        val bookmarkedPackage=getWorkspace("?package=identity")
        assert(bookmarkedPackage.contains("identity package workspace") && bookmarkedPackage.contains(client.inspect("identity").revision.id))
        assert(bookmarkedPackage.contains("/?package=identity&amp;file=Retained_Identity.thy") && bookmarkedPackage.contains("Declared capabilities"))
        val impactPage=getWorkspace("?package=identity&view=impact")
        assert(impactPage.contains("Change impact for identity") && impactPage.contains("transitive → consumer → identity"))
        assert(impactPage.contains("does not predict native result invalidation") && impactPage.contains(client.inspect("consumer").revision.id))
        assert(getWorkspace("?package=custom&view=impact").contains("impact was not computed"))
        val bookmarkedSource=getWorkspace("?package=custom&file=Custom.thy")
        assert(bookmarkedSource.contains("Back to custom package workspace") && bookmarkedSource.contains("lemma preserved: True by simp"))
        assert(bookmarkedSource.contains("Review a source change"))
        val bookmarkedMigration=getWorkspace("?package=paint&view=migration")
        assert(bookmarkedMigration.contains("Back to paint package workspace") && bookmarkedMigration.contains("v7_math_formula litres_scalar"))
        val form="token="+token+"&action=Open&draft=custom&file=Custom.thy"
        val opened=http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url))
          .POST(java.net.http.HttpRequest.BodyPublishers.ofString(form)).build(),java.net.http.HttpResponse.BodyHandlers.ofString())
        assert(opened.body().contains("lemma preserved: True by simp"))
        val inspected=http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url))
          .POST(java.net.http.HttpRequest.BodyPublishers.ofString("token="+token+"&action=Inspect&draft=custom")).build(),java.net.http.HttpResponse.BodyHandlers.ofString())
        assert(inspected.body().contains("name=\"file\" value=\"Custom.thy\""))
        assert(inspected.body().contains("Source-only workspace"))
        val growthPage=http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url))
          .POST(java.net.http.HttpRequest.BodyPublishers.ofString("token="+token+"&action=Inspect&draft=identity")).build(),java.net.http.HttpResponse.BodyHandlers.ofString())
        assert(growthPage.body().contains("Retained_Identity.thy") && growthPage.body().contains("inspection does not establish native admission"))
        val migration=http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url))
          .POST(java.net.http.HttpRequest.BodyPublishers.ofString("token="+token+"&action=Migration&draft=paint")).build(),java.net.http.HttpResponse.BodyHandlers.ofString())
        assert(migration.body().contains("v7_math_formula litres_scalar") && migration.body().contains("Remaining obligations") && migration.body().contains("zero spread rate"))
        def savePage(page:String,replacement:String):String={
          def hidden(name:String):String=("name=\""+name+"\" value=\"([^\"]*)").r.findFirstMatchIn(page).get.group(1)
          val values=Vector("token"->token,"action"->"Save","draft"->"custom","file"->"Custom.thy",
            "manifest"->hidden("manifest"),"revision"->hidden("revision"),"original"->hidden("original"),"replacement"->replacement)
          val encoded=values.map((key,value)=>java.net.URLEncoder.encode(key,UTF_8)+"="+java.net.URLEncoder.encode(value,UTF_8)).mkString("&")
          http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url))
            .POST(java.net.http.HttpRequest.BodyPublishers.ofString(encoded)).build(),java.net.http.HttpResponse.BodyHandlers.ofString()).body()
        }
        val firstSave=savePage(opened.body(),next.text+"(* first browser save *)\n")
        assert(firstSave.contains("Saved."))
        val secondSave=savePage(firstSave,next.text+"(* second browser save *)\n")
        assert(secondSave.contains("Saved.") && client.source("custom","Custom.thy").text.contains("second browser save"))
        val revisitedSource=getWorkspace("?package=custom&file=Custom.thy")
        assert(revisitedSource.contains("second browser save") && revisitedSource.contains(client.inspect("custom").revision.id))
        assert(getWorkspace("?package=custom").contains(client.inspect("custom").revision.id))
        def submit(values:Map[String,String]):String={
          val encoded=(values+("token"->token)).toVector.map((key,value)=>java.net.URLEncoder.encode(key,UTF_8)+"="+java.net.URLEncoder.encode(value,UTF_8)).mkString("&")
          http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url))
            .POST(java.net.http.HttpRequest.BodyPublishers.ofString(encoded)).build(),java.net.http.HttpResponse.BodyHandlers.ofString()).body()
        }
        def reviewedPayload(marker:String,draft:String="custom"):Map[String,String]={
          val source=client.source(draft,"Custom.thy")
          Map("draft"->draft,"file"->"Custom.thy","manifest"->source.snapshot.manifest,"revision"->source.snapshot.revision.id,
            "obligation"->"Document the example","context"->"unreviewed","start"->"0","stop"->source.entry.content.size.toString,
            "choice"->"Example","meaning"->"PreserveMeaning","reason"->"Add an explanatory source comment","replacement"->(source.text+marker+"\n"))
        }
        def preview(payload:Map[String,String]):String={
          val page=submit(payload+("action"->"Preview source change"))
          assert(page.contains("Review source change") && page.contains("Native revalidation remains a separate operation"))
          "name=\"review\" value=\"([^\"]+)".r.findFirstMatchIn(page).get.group(1)
        }
        val reviewed=reviewedPayload("(* reviewed example *)")
        val reviewedId=preview(reviewed)
        val applied=submit(reviewed++Map("action"->"Apply reviewed change","review"->reviewedId))
        assert(applied.contains("Saved.") && client.source("custom","Custom.thy").text.contains("reviewed example"))
        assert(submit(reviewed++Map("action"->"Apply reviewed change","review"->reviewedId)).contains("already used"))
        val cancelled=reviewedPayload("(* must not be applied *)")
        val cancelledId=preview(cancelled)
        assert(submit(Map("action"->"Cancel reviewed change","review"->cancelledId)).contains("No source change was applied"))
        val expiredPage=submit(cancelled++Map("action"->"Apply reviewed change","review"->cancelledId))
        assert(expiredPage.contains("already used") && expiredPage.contains("Your submitted replacement") && expiredPage.contains("(* must not be applied *)"))
        assert(!client.source("custom","Custom.thy").text.contains("must not be applied"))
        val tamper=reviewedPayload("(* consented text *)")
        val tamperId=preview(tamper)
        assert(submit(tamper++Map("action"->"Apply reviewed change","review"->tamperId,"replacement"->"unreviewed text")).contains("Review expired, changed or already used"))
        assert(!client.source("custom","Custom.thy").text.contains("unreviewed text"))
        val staleProposal=reviewedPayload("(* stale proposal *)")
        val staleReviewId=preview(staleProposal)
        val concurrent=client.source("custom","Custom.thy")
        client.edit("concurrentReview", "custom",concurrent.snapshot.manifest,concurrent.snapshot.revision.id,"Custom.thy",0,
          concurrent.entry.content.size,concurrent.entry.content.bytes,(concurrent.text+"(* newer source *)\n").getBytes(UTF_8))
        val stalePage=submit(staleProposal++Map("action"->"Apply reviewed change","review"->staleReviewId))
        assert(stalePage.contains("Source changed") && stalePage.contains("Your submitted replacement") && stalePage.contains("(* stale proposal *)"))
        assert(stalePage.contains("Open current source") && !stalePage.contains("(* newer source *)"))
        val openedCurrent=submit(Map("action"->"Open current source","draft"->"custom","file"->"Custom.thy"))
        assert(openedCurrent.contains("(* newer source *)") && !openedCurrent.contains("(* stale proposal *)"))
        assert(client.source("custom","Custom.thy").text.contains("newer source") && !client.source("custom","Custom.thy").text.contains("stale proposal"))
        client.importSource("reviewForgetImport","review-forget",source,Intake.Format.NativeDevelopment)
        val forgottenReview=reviewedPayload("(* forgotten review *)","review-forget")+("replacement"->"(* only the submitted proposal survives *)")
        val forgottenReviewId=preview(forgottenReview)
        managed.forget("review-forget")
        val forgottenPage=submit(forgottenReview++Map("action"->"Apply reviewed change","review"->forgottenReviewId))
        assert(forgottenPage.contains("Package unavailable") && forgottenPage.contains("Your submitted replacement"))
        assert(forgottenPage.contains("only the submitted proposal survives") && !forgottenPage.contains("lemma preserved"))
        assert(!forgottenPage.contains("<h3>Original</h3>"))
        assert(!client.list().contains("review-forget"))
        val forgottenBookmark=getWorkspace("?package=review-forget&file=Custom.thy")
        assert(forgottenBookmark.contains("Package unavailable") && !forgottenBookmark.contains("lemma preserved"))
        val consumerSource=client.source("consumer","package.json")
        val revisedDescriptor=consumerSource.text.replace("[{\"package_id\":\"veri7vn.retained-identity\",\"version\":\"0.1.0\"}]","[]")
        assert(revisedDescriptor!=consumerSource.text)
        client.edit("remove-dependency","consumer",consumerSource.snapshot.manifest,consumerSource.snapshot.revision.id,"package.json",0,consumerSource.entry.content.size,consumerSource.entry.content.bytes,revisedDescriptor.getBytes(UTF_8))
        val revisedImpact=getWorkspace("?package=identity&view=impact")
        assert(!revisedImpact.contains("transitive → consumer → identity"))
        assert(client.impact("identity").affected.isEmpty)
        managed.forget("identity")
        assert(getWorkspace("?package=identity&view=impact").contains("impact was not computed"))
        val denied=http.send(java.net.http.HttpRequest.newBuilder(java.net.URI.create(browser.url))
          .POST(java.net.http.HttpRequest.BodyPublishers.ofString("action=Open&draft=custom&file=Custom.thy")).build(),java.net.http.HttpResponse.BodyHandlers.ofString())
        assert(denied.body().contains("Expired form") && !denied.body().contains("lemma preserved"))
      }finally browser.close()
    } finally store.close()
    val reopened=new WorkspaceStore(root)
    val persisted=try new Authoring(new ManagedSources(reopened)).source("custom","Custom.thy") finally reopened.close()
    assert(persisted.text.contains("lemma preserved"))
    val stdout=new java.io.ByteArrayOutputStream()
    Console.withOut(new java.io.PrintStream(stdout,true,"UTF-8")) {
      veri7vn.cli.Workbench.run(Array(root.toString,"list"))
      veri7vn.cli.Workbench.run(Array(root.toString,"inspect","custom"))
      veri7vn.cli.Workbench.run(Array(root.toString,"impact","consumer"))
      val proposal=Files.createTempFile("v7-reviewed-comment-",".txt")
      Files.write(proposal,"(* CLI reviewed source *)".getBytes(UTF_8))
      Console.withIn(new java.io.ByteArrayInputStream("cancel\n".getBytes(UTF_8))) {
        veri7vn.cli.Workbench.run(Array(root.toString,"review","custom","Custom.thy","0","1","CLI note","Example","PreserveMeaning","Review source",proposal.toString,"cliReviewCancel"))
      }
      Files.delete(proposal)
      val expected=Files.createTempFile("v7-cli-expected-",".thy")
      val replacement=Files.createTempFile("v7-cli-replacement-",".thy")
      try {
        Files.write(expected,persisted.entry.content.bytes)
        Files.write(replacement,(persisted.text+"(* actual CLI edit *)\n").getBytes(UTF_8))
        veri7vn.cli.Workbench.run(Array(root.toString,"edit","custom",persisted.snapshot.manifest,persisted.snapshot.revision.id,"Custom.thy","0",persisted.entry.content.size.toString,expected.toString,replacement.toString,"cliActualEdit"))
      } finally {Files.delete(expected);Files.delete(replacement)}
    }
    assert(stdout.toString("UTF-8").contains("custom") && stdout.toString("UTF-8").contains("Custom.thy"))
    assert(stdout.toString("UTF-8").contains("Inspected dependency path: transitive") && stdout.toString("UTF-8").contains("does not predict native result invalidation"))
    val finalStore=new WorkspaceStore(root)
    try assert(new Authoring(new ManagedSources(finalStore)).source("custom","Custom.thy").text.contains("actual CLI edit")) finally finalStore.close()
    println("AUTHORING_CLIENT_PASS actual native edit stale conflict original paint18 listing forget overflow browser CLI restart")
  }
}
