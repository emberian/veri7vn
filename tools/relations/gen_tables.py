#!/usr/bin/env python3
"""gen_tables - write src/extract/relations/Relation_Tables.thy: the 161 relation specialists' tables as HOL data.

For each upstream/root/specialists/rel-*/ (read-only): the reader keys of readers.json in their shipped loop order,
the property each key reads and its forward/inverse phrasing counts (relation_readers_v1.PROPS, as
relation_spec_v2.compiled reads them), the dropped phrasings of readers.json, the domain's roots / occupation roots /
excluded properties (the overlay's relation_domains_v2.json, which equals the manifest's domain block for all 161),
and whether the organ class is the pronoun-guard subclass. src/extract/relations/tables_check.py re-reads the
shipped files independently and compares them with the HOL text, so this generator is not trusted either.

  python3 -I tools/relations/gen_tables.py
"""
import json
import os
import sys

sys.dont_write_bytecode = True
REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
UP = "/Users/ember/dev/o7vn/upstream/root"
sys.path.insert(0, UP + "/wander-train")
import relation_readers_v1 as RD  # noqa: E402

SPEC = UP + "/specialists"
DOMS = os.path.join(REPO, "var/linker/o7root/relstore/relation_domains_v2.json")
OUT = os.path.join(REPO, "src/extract/relations/Relation_Tables.thy")


def key_of(k):
    return k if isinstance(k, str) and not k.lstrip("-").isdigit() else int(k)


def nl(xs):
    return "[" + ", ".join(str(int(x)) for x in xs) + "]"


def main():
    doms = {d["id"]: d for d in json.load(open(DOMS))}
    lines = []
    for sid in sorted(x for x in os.listdir(SPEC) if x.startswith("rel-")):
        d = os.path.join(SPEC, sid)
        man = json.load(open(os.path.join(d, "manifest.json")))
        r = json.load(open(os.path.join(d, "readers.json")))
        dom = doms[man["organ"]["init"]["domain"]]
        rds = []
        for k in r["keys"]:
            e = RD.PROPS[key_of(k)]
            dr = [(dd, int(i)) for kk, dd, i in r.get("dropped", []) if str(kk) == str(k)]
            rds.append("mk_reader (STR ''%s'') %d %d %d %s %s" % (
                k, int(e.get("prop", key_of(k))), len(e.get("fwd", [])), len(e.get("inv", [])),
                nl(sorted(i for dd, i in dr if dd == "fwd")), nl(sorted(i for dd, i in dr if dd == "inv"))))
        guard = man["organ"]["class"] == "RelationOrganV2G"
        lines.append("    mk_spec (STR ''%s'') [%s] %s %s %s %s" % (
            sid, ", ".join(rds), nl(dom.get("roots", [])), nl(dom.get("occ", [])), nl(dom.get("exclude_props", [])),
            "True" if guard else "False"))
    thy = r'''theory Relation_Tables
  imports Relation_Reader
begin

text \<open>GENERATED by tools/relations/gen_tables.py from the shipped specialist folders; checked against them
by src/extract/relations/tables_check.py. One entry per relation specialist: its id, its readers in the shipped
loop order (key, property read, forward phrasings, inverse phrasings, dropped forward and inverse phrasing
indices), its domain (root classes, occupation roots, excluded properties) and whether the pronoun guard of
RelationOrganV2G applies.\<close>

definition mk_reader :: "String.literal \<Rightarrow> natural \<Rightarrow> natural \<Rightarrow> natural \<Rightarrow> natural list \<Rightarrow> natural list \<Rightarrow> reader" where
  "mk_reader k p nf ni df di = \<lparr>rkey = k, rprop = p, nfwd = nf, ninv = ni, dfwd = df, dinv = di\<rparr>"

definition mk_spec :: "String.literal \<Rightarrow> reader list \<Rightarrow> natural list \<Rightarrow> natural list \<Rightarrow> natural list \<Rightarrow> bool \<Rightarrow> spec" where
  "mk_spec n rs ro oc ex g = \<lparr>sid = n, readers = rs, roots = ro, occs = oc, excl = ex, guard = g\<rparr>"

definition specs :: "spec list" where
  "specs = [
%s
  ]"

definition spec_of :: "String.literal \<Rightarrow> spec option" where
  "spec_of n = find (\<lambda>sp. sid sp = n) specs"

lemma spec_of_Some: "spec_of n = Some sp \<Longrightarrow> sp \<in> set specs \<and> sid sp = n"
  using find_Some_mem by (fastforce simp: spec_of_def)

end
''' % ",\n".join(lines)
    open(OUT, "w", encoding="utf-8").write(thy)
    print("wrote %s: %d specialists" % (OUT, len(lines)))


if __name__ == "__main__":
    main()
