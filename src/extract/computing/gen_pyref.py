#!/usr/bin/env python3
"""Generate Pyref_Table.thy from upstream/root/specialists/python/pyref_v1.json (856 rows).
Each row: (name, prefix, short, module, signature, doc); prefix is name.rsplit('.',1)[0] or ''.
Strings are ASCII; a quote, double quote or backslash is spliced in from apos/dquote/bsl."""
import json
from pathlib import Path
REPO = Path(__file__).resolve().parents[3]
d = json.load(open(REPO / "upstream/root/specialists/python/pyref_v1.json"))
ver, ents = d["python"], d["entries"]

def lit(s):
    s = s or ""
    assert all(32 <= ord(c) < 127 for c in s), s
    out, cur = [], ""
    def flush():
        nonlocal cur
        if cur:
            out.append("STR ''%s''" % cur)
            cur = ""
    for c in s:
        if c == "'": flush(); out.append("apos")
        elif c == '"': flush(); out.append("dquote")
        elif c == "\\": flush(); out.append("bsl")
        else: cur += c
    flush()
    return " + ".join(out) if out else "STR ''''"

rows = []
for name, e in ents.items():
    assert e["name"] == name
    pre, _, short = name.rpartition(".")
    rows.append("(%s, %s, %s, %s, %s, %s)" % tuple(lit(x) for x in (name, pre, short, e["module"], e["signature"], e["doc"])))
body = ",\n   ".join(rows)
Path(__file__).with_name("Pyref_Table.thy").write_text(
"""theory Pyref_Table
  imports Computing_Num
begin

text \\<open>Generated by gen_pyref.py from upstream/root/specialists/python/pyref_v1.json
(Python %s, %d rows; python and python-r2 ship the same file). A row is
(name, prefix, short, module, signature, doc); an absent signature or
docstring is the empty string. tables_check.py compares this text with the
JSON.\\<close>

definition bsl :: String.literal where "bsl = String.implode [CHR 0x5C]"

definition py_version :: String.literal where "py_version = STR ''%s''"

definition py_entries :: "(String.literal \\<times> String.literal \\<times> String.literal \\<times> String.literal \\<times> String.literal \\<times> String.literal) list" where
  \\<open>py_entries = [
   %s]\\<close>

end
""" % (ver, len(rows), ver, body))
print(len(rows), "rows")
