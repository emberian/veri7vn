#!/usr/bin/env python3
"""Generate Guards_Vectors.thy: one feats literal per recorded core-panel item,
pinned to the guard decision the binary produced on it.

Inputs (run from the worktree root):
  src/extract/guards/inputs114.jsonl   the raw items (question, route, reply,
                                       relstore facts) - replay.py --emit-inputs
  var/guards/bin/guards                the compiled recognizer + kernel
The binary is asked twice per item: --dump-feats (the recognizer's feature
vector) and the decision mode (the kernel's verdict). The generated theory
states, per item, that decision_auto on exactly that vector returns exactly
that verdict, and the Isabelle session proves it by eval. If the proved kernel
and the exported kernel ever disagree, the build goes red.

The vectors are UNTRUSTED recognizer output (the theorem is about the kernel's
behaviour on them, not about the recognizer). Regenerate after any recognizer
change:
  /Users/ember/dev/o7vn/.venv/bin/python -I src/extract/guards/gen_vectors.py
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORKTREE = HERE.parents[2]
BIN = WORKTREE / "var" / "guards" / "bin" / "guards"
INPUTS = HERE / "inputs114.jsonl"


def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def hstr(s: str) -> str:
    return "''%s''" % esc(s)


def hstrs(xs) -> str:
    return "[" + ", ".join(hstr(x) for x in xs) + "]"


def hbools(bs) -> str:
    return " ".join("True" if b else "False" for b in bs)


def hrats(pairs) -> str:
    return "[" + ", ".join("(Fract (%d::int) (%d::int))" % (a, b) for a, b in pairs) + "]"


def hchars(s: str) -> str:
    return "[" + ", ".join("CHR %s" % hstr(c) for c in s) + "]"


def main() -> int:
    lines = INPUTS.read_text().splitlines()
    feats = subprocess.run([str(BIN), "--dump-feats"], input="\n".join(lines),
                           capture_output=True, text=True, check=True).stdout.splitlines()
    verdicts = subprocess.run([str(BIN)], input="\n".join(lines),
                              capture_output=True, text=True, check=True).stdout.splitlines()
    feats = [json.loads(l) for l in feats]
    verdicts = [json.loads(l) for l in verdicts]
    assert len(feats) == len(verdicts) == 114, (len(feats), len(verdicts))

    out = []
    out.append("(* GENERATED by src/extract/guards/gen_vectors.py from the recognizer's")
    out.append("   dump on the 114 recorded core-panel items. One feats literal per")
    out.append("   item, pinned to the decision the kernel produced on it. The vectors")
    out.append("   are untrusted recognizer output; do not edit, regenerate. *)")
    out.append("theory Guards_Vectors")
    out.append("  imports Guards")
    out.append("begin")
    out.append("")
    rows = []
    for f, v in zip(feats, verdicts):
        i = f["id"]
        prem = "None"
        if f["premise"]:
            p = f["premise"]
            prem = "(Some (%s, (%d::int), %s))" % (
                hstr(p["label"]), p["year"],
                "[" + ", ".join("(%d::int)" % y for y in p["years"]) + "]")
        hum = "None" if f["human"] is None else ("(Some " + ("True" if f["human"] else "False") + ")")
        f510, f511, f513, f514 = f["f510"], f["f511"], f["f513"], f["f514"]
        f516, f517, f532, f533, f534 = f["f516"], f["f517"], f["f532"], f["f533"], f["f534"]
        opt13 = "None" if f513[5] is None else "(Some " + hstr(f513[5]) + ")"
        opt14 = "None" if f514[3] is None else "(Some " + hstr(f514[3]) + ")"
        lit = "\n     ".join([
            "Feats %s %s %s %s %s %s %s %s %s" % (
                "True" if f["answered"] else "False", hstr(f["route"]), hstr(f["resp_g3"]),
                hstr(f["resp_q"]), hstr(f["resp_r"]), hrats(f["nums_q"]), hrats(f["nums_resp"]),
                hum, prem),
            "(F510 %s %s %s)" % ("True" if f510["gate"] else "False",
                                 hstrs(f510["specifics"]),
                                 "[" + ", ".join(hstrs(ph) for ph in f510["of_phrases"]) + "]"),
            "(F511 %s)" % hbools(f511),
            "(F513 %s)" % (hbools(f513[:3]) + " " + hstrs(f513[3]) + " "
                           + ("True" if f513[4] else "False") + " " + opt13),
            "(F514 %s)" % (("True" if f514[0] else "False") + " " + hstrs(f514[1]) + " "
                           + ("True" if f514[2] else "False") + " " + opt14),
            "(F516 %s %s)" % (hbools(f516[:4]), hstrs(f516[4])),
            "(F517 %s)" % hbools(f517),
            "(F532 %s)" % hbools(f532),
            "(F533 %s %s %s %s)" % (hbools(f533[:3]), hchars(f533[7]), hchars(f533[8]),
                                    hbools(f533[3:7])),
            "(F534 %s)" % hbools(f534)])
        out.append("definition v%d :: feats where" % i)
        out.append('  "v%d = %s"' % (i, lit))
        out.append("")
        LC = {"w510": "L510", "w511": "L511", "w513": "L513", "w514": "L514", "w516": "L516",
              "w517": "L517", "w532": "L532", "w533own": "L533own", "w534": "L534"}
        if v.get("code"):
            rows.append("(v%d, Some (%s, %s))" % (i, LC[v["layer"]], v["code"]))
        else:
            rows.append("(v%d, None)" % i)
    out.append("definition vectors :: \"(feats * (layer * gcode) option) list\" where")
    out.append('  "vectors = [%s]"' % (",\n   ".join(rows)))
    out.append("")
    out.append("theorem vectors_pin:")
    out.append('  "list_all (\\<lambda>(v, r). decision_auto v = r) vectors"')
    out.append("  by code_simp")
    out.append("")
    out.append("theorem vectors_count: \"length vectors = 114\"")
    out.append("  by code_simp")
    out.append("")
    out.append("end")
    out.append("")
    (HERE / "Guards_Vectors.thy").write_text("\n".join(out), encoding="utf-8")
    print("wrote Guards_Vectors.thy (%d vectors)" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
