"""Extract the full precision-guard inventory from the upstream fold modules.

For every fold that emits a precision_guard path: the rule codes it can emit
(found by walking the module's AST for the string constants that reach a
`precision_guard:%s`-style withhold: `return "CODE"` inside a guard function,
`_withhold(out, "CODE", ...)`, `_withhold(out, "CODE")`, and the literal
`precision_guard:CODE` forms), plus its position in the chain (from
audit/folds/folds.json). Output: catalogue.json, the ground truth that
tables_check.py compares against the HOL-exported catalogue.

Read-only against upstream. Run with the repo venv python:
  /Users/ember/dev/o7vn/.venv/bin/python -I src/extract/guards/extract_catalogue.py
"""
from __future__ import annotations

import ast
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORKTREE = HERE.parents[2]
UP = Path(os.environ.get("GT_UPSTREAM", "/Users/ember/dev/o7vn/upstream"))
ADMITTED = UP / "root" / "fable-content" / "oracle-m-series-2026-08-15" / "self_loop" / "admitted"

sys.dont_write_bytecode = True

CODE_RE = re.compile(r"^[A-Z][A-Za-z0-9]*_[a-z][A-Za-z0-9_]*$")


def fold_codes(path: Path) -> list[str]:
    """rule codes this fold can emit, in source order."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    codes: list[str] = []

    def add(s):
        if CODE_RE.match(s) and s not in codes:
            codes.append(s)

    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str):
            s = node.value
            # literal forms: "precision_guard:CODE" and "precision_guard:CODE>%s"
            for m in re.findall(r"precision_guard:([A-Za-z0-9_]+)", s):
                add(m)
        if isinstance(node, ast.Call):
            f = node.func
            # _withhold(out, "CODE", ...) / guard8-style helpers
            if isinstance(f, ast.Name) and f.id in ("_withhold", "_withhold_out") \
                    and len(node.args) >= 2 and isinstance(node.args[1], ast.Constant):
                add(str(node.args[1].value))
    # returns of bare code strings inside functions whose name mentions guard/rule
    for node in ast.walk(tree):
        if isinstance(node, ast.Return) and isinstance(node.value, ast.Constant) \
                and isinstance(node.value.value, str):
            s = node.value.value
            if CODE_RE.match(s) and "_" in s[1:]:
                add(s)
    return codes


def collect():
    folds = json.load(open(WORKTREE / "audit" / "folds" / "folds.json"))["folds"]
    bymod = {f["module"]: f for f in folds}
    # chain position: distance from the tip (0 = tip w540); larger = deeper = runs earlier
    cur, chain = "oracle_release_runtime_w540", []
    while cur in bymod:
        chain.append(cur)
        b = bymod[cur]["base_module"]
        if not b or b == cur:
            break
        cur = b
    pos = {m: i for i, m in enumerate(chain)}

    out = []
    for p in sorted(ADMITTED.glob("oracle_release_runtime_*.py")):
        src = p.read_text(encoding="utf-8")
        if "precision_guard" not in src:
            continue
        codes = fold_codes(p)
        if not codes:
            continue
        m = p.stem
        out.append({"module": m, "chain_pos": pos.get(m),
                    "file": "upstream/root/fable-content/oracle-m-series-2026-08-15/self_loop/admitted/" + p.name,
                    "codes": sorted(codes)})
    out.sort(key=lambda r: (r["chain_pos"] if r["chain_pos"] is not None else 999, r["module"]))
    return out


def write_thy(out):
    """Guards_Catalogue.thy: the inventory as one HOL constant. Generated; do
    not edit. Regenerate with  extract_catalogue.py --thy ; tables_check.py
    checks the committed file against the Python source."""
    rows = []
    for r in out:
        for c in r["codes"]:
            rows.append("(''%s'', ''%s'', %d)" % (c, r["module"], r["chain_pos"]))
    n = len(rows)
    body = ",\n  ".join(rows)
    dst = HERE / "Guards_Catalogue.thy"
    dst.write_text(
        "(* GENERATED by src/extract/guards/extract_catalogue.py --thy from the upstream\n"
        "   fold sources. One row per guard code the chain can emit: code, module,\n"
        "   chain position (0 = tip w540, larger = deeper = sees a reply earlier).\n"
        "   %d folds, %d codes. Do not edit; regenerate. *)\n"
        "theory Guards_Catalogue\n"
        "  imports Main\n"
        "begin\n\n"
        "definition catalogue :: \"(string * string * int) list\"\n"
        "  where\n" % (len(out), n), encoding="utf-8")
    with open(dst, "a", encoding="utf-8") as f:
        f.write("  \"catalogue =\n  [%s]\"\n\nend\n" % body)
    print("wrote %s (%d rows)" % (dst, n))


def main():
    out = collect()
    dst = HERE / "catalogue.json"
    json.dump(out, open(dst, "w"), indent=1)
    n = sum(len(r["codes"]) for r in out)
    print("%d folds, %d codes -> %s" % (len(out), n, dst))
    if "--thy" in sys.argv:
        write_thy(out)
    for r in out:
        print("%3d %-42s %s" % (r["chain_pos"], r["module"], " ".join(r["codes"])))


if __name__ == "__main__":
    main()
