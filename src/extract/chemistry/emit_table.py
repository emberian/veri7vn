#!/usr/bin/env python3
"""Emit base/Chem_Table.thy from PubChem's periodic-table CSV (the one the organs read).
tables_check.py re-reads the CSV and the emitted theory and fails on any difference."""
import csv, sys
from fractions import Fraction as Fr
from pathlib import Path
REPO = Path(__file__).resolve().parents[3]
CSV = REPO / "upstream/root/specialists/chemistry-v3/pubchem_periodic_table.csv"

def lit(s): return "STR ''%s''" % s
def rat(s):
    f = Fr(s); return "(%d / %d)" % (f.numerator, f.denominator)
def main():
    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    out = ["theory Chem_Table\n  imports Chem_Util\nbegin\n",
"""text \\<open>PubChem's periodic table (118 elements) as the Oracle7 chemistry organs
read it: every property is the CSV's own text; the atomic mass and the melting
and boiling points are also given as exact rationals (the decimal the CSV
writes). Generated by emit_table.py from
upstream/root/specialists/chemistry-v3/pubchem_periodic_table.csv; tables_check.py
compares this file with the CSV.\\<close>

datatype pelem = PElem (pnum: nat) (psym: string) (pname: String.literal) (plow: String.literal)
  (pmass_s: String.literal) (pmass: rat) (pconf: String.literal) (pen: String.literal)
  (pip: String.literal) (pstate: String.literal) (pmp: String.literal) (pmp_r: rat)
  (pbp: String.literal) (pbp_r: rat) (pdens: String.literal) (pblock: String.literal)
  (pyear: String.literal)

definition ptable :: "pelem list" where
  "ptable = [
"""]
    items = []
    for r in rows:
        mp = rat(r["MeltingPoint"]) if r["MeltingPoint"] else "0"
        bp = rat(r["BoilingPoint"]) if r["BoilingPoint"] else "0"
        items.append("  PElem %s ''%s'' (%s) (%s) (%s) %s (%s) (%s) (%s) (%s) (%s) %s (%s) %s (%s) (%s) (%s)" % (
            r["AtomicNumber"], r["Symbol"], lit(r["Name"]), lit(r["Name"].lower()), lit(r["AtomicMass"]), rat(r["AtomicMass"]),
            lit(r["ElectronConfiguration"]), lit(r["Electronegativity"]), lit(r["IonizationEnergy"]), lit(r["StandardState"]),
            lit(r["MeltingPoint"]), mp, lit(r["BoilingPoint"]), bp, lit(r["Density"]), lit(r["GroupBlock"]), lit(r["YearDiscovered"])))
    out.append(",\n".join(items) + "]\"\n\nend\n")
    (Path(__file__).resolve().parent / "base/Chem_Table.thy").write_text("".join(out), encoding="utf-8")
main()
